export const LAN_PACKS = { zh, en, tw };

export type LanKey = keyof typeof zh;

export type LanT = (key: LanKey, params?: Record<string, string | number>) => string;

const fill = (text: string, params?: Record<string, string | number>) => {
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, (whole, name: string) =>
        Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : whole,
    );
};

/** A `t` for the props-style components in this feature, so a page never
 *  reaches into the module while rendering. */
export function lanT(lang: LanLang): LanT {
    const pack = LAN_PACKS[lang] ?? zh;
    return (key, params) => fill(pack[key] ?? zh[key] ?? key, params);
}

export const LAN_LANGS: Array<{ id: LanLang; label: string }> = [
    { id: "zh", label: "简体中文" },
    { id: "tw", label: "繁體中文" },
    { id: "en", label: "English" },
];

/** 「app.language」 has two homes: the database row, which is what the clipboard
 *  window reads, and the localStorage mirror a window that opens before the
 *  database has answered can still use. Anything unknown is 中文, the language
 *  this feature was written in. */
export function readLanLang(settings: Record<string, string>): LanLang {
    const stored = (settings["app.language"] ?? localStorage.getItem("tiez_language") ?? "zh") as LanLang;
    return LAN_LANGS.some((lang) => lang.id === stored) ? stored : "zh";
}
