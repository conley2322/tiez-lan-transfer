export const getEmojiName = (emoji: string, locale: Locale | string = "zh", fallbackGroupName?: string): string => {
  const item = EMOJI_NAMES[emoji];
  if (item) {
    if (locale === "zh-TW") return item["zh-TW"] || item.zh || item.en;
    if (locale === "en") return item.en || item.zh;
    return item.zh || item["zh-TW"] || item.en;
  }
  return fallbackGroupName ? `${fallbackGroupName} 表情` : "表情";
};
